//! Optional Apollo Federation v2 subgraph (feature `graphql`, ADR-0011).
//!
//! When the feature is compiled and `GRAPHQL_ENABLED` is not `false`, the
//! service exposes `POST`/`GET /graphql` next to its REST surface. The endpoint
//! requires `Authorization: Bearer <JWT>`: the token is validated against
//! `GRAPHQL_JWKS_URL`, `GRAPHQL_JWT_ISSUER`, `GRAPHQL_JWT_AUDIENCE` and
//! `GRAPHQL_JWT_CLIENT_ID` before the GraphQL request runs, and the caller
//! lands in the GraphQL context as [`auth::AuthContext`]. Missing/invalid
//! tokens get problem+json 401 (with a `WWW-Authenticate: Bearer` challenge);
//! a JWKS fetch failure gets 503.
//!
//! The schema is in [`schema`]: an `Order` entity with `@key(fields: "id")`,
//! resolved through a [`schema::OrderLoader`] data loader, a `User` reference
//! with `@key(fields: "id", resolvable: false)` owned by the users subgraph,
//! and `_service { sdl }`/`_entities` generated by async-graphql.

pub mod auth;
pub mod schema;

use std::sync::Arc;

use async_graphql::ParseRequestError;
use async_graphql_axum::{GraphQLRequest, GraphQLResponse};
use axum::Router;
use axum::extract::State;
use axum::http::StatusCode;
use axum::response::{IntoResponse, Response};
use axum::routing::get;

use crate::config::GraphQLConfig;
use crate::problem::{ApiError, Problem};
use crate::server::AppState;
use crate::services::orders::OrdersService;
use auth::{AuthContext, JwtVerifier};
use schema::{OrderLoader, ServiceSchema};

/// State shared by the GraphQL handler: the schema and the token verifier.
#[derive(Clone)]
pub struct GraphQLState {
    pub(crate) schema: ServiceSchema,
    pub(crate) verifier: Arc<JwtVerifier>,
}

impl GraphQLState {
    /// Builds the schema and token verifier from `GRAPHQL_*` configuration.
    pub fn new(config: &GraphQLConfig, orders: Arc<OrdersService>) -> Self {
        Self {
            schema: schema::schema(orders),
            verifier: Arc::new(JwtVerifier::new(config)),
        }
    }

    /// The federation schema, exposed for tests and schema tooling.
    pub fn schema(&self) -> &ServiceSchema {
        &self.schema
    }
}

/// Routes owned by the GraphQL module, merged into the app only when enabled.
pub fn routes() -> Router<AppState> {
    Router::new().route("/graphql", get(handler).post(handler))
}

async fn handler(
    State(state): State<AppState>,
    auth: AuthContext,
    request: GraphQLRequest<GraphQLRejection>,
) -> Result<GraphQLResponse, ApiError> {
    let graphql = state.graphql()?;
    let orders = state
        .orders
        .as_ref()
        .cloned()
        .ok_or_else(|| ApiError::ServiceUnavailable("orders are not configured".to_owned()))?;
    let request = request.into_inner().data(auth).data(orders.clone()).data(
        async_graphql::dataloader::DataLoader::new(OrderLoader::new(orders), tokio::spawn),
    );

    Ok(graphql.schema.execute(request).await.into())
}

/// Body-parse rejection for [`GraphQLRequest`], mapped onto the ADR-0005
/// problem contract instead of async-graphql-axum's plain-text defaults.
struct GraphQLRejection(ParseRequestError);

impl From<ParseRequestError> for GraphQLRejection {
    fn from(error: ParseRequestError) -> Self {
        Self(error)
    }
}

impl IntoResponse for GraphQLRejection {
    fn into_response(self) -> Response {
        match self.0 {
            ParseRequestError::PayloadTooLarge => {
                tracing::debug!("GraphQL request body exceeds the configured limit");
                Problem::new(StatusCode::PAYLOAD_TOO_LARGE)
                    .with_detail("GraphQL request body is too large")
                    .into_response()
            }
            // Parse errors can quote the body; keep the detail generic.
            error => {
                tracing::debug!(error = %error, "malformed GraphQL request");
                Problem::new(StatusCode::BAD_REQUEST)
                    .with_detail("malformed GraphQL request")
                    .into_response()
            }
        }
    }
}
